// Generates src/styles/themes.css from src/styles/tokens.json.
// Themes: tool (default, «Инструмент»), gm-table («Стол мастера»), paper («Бумажный лист», also print).
// Each has light/dark schemes selected by [data-scheme] on <html>.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, '../src/styles/tokens.json'), 'utf8'));
const map = { tool: 'dir1-tool', 'gm-table': 'dir3-gm-table', paper: 'dir2-paper' };
const px = (v) => `${v}px`;

const sh = tokens.shared;
const lines = ['/* AUTO-GENERATED by scripts/gen-themes.mjs from tokens.json — do not edit. */', ':root {'];
for (const k of ['xs', 'sm', 'md', 'lg', 'xl', 'radiusSm', 'radiusMd', 'fieldH', 'iconBtn', 'rowHTouch'])
  lines.push(`  --${k}: ${px(sh[k])};`);
lines.push(`  --grid-columns: ${sh.grid.columns};`);
lines.push(`  --grid-margin: var(--${sh.grid.margin});`);
lines.push(`  --grid-gutter: var(--${sh.grid.gutter});`);
lines.push('}');

function colorBlock(c) {
  return Object.entries(c).map(([k, v]) => `  --color-${k}: ${v};`);
}
function themeVars(d) {
  const f = d.fonts;
  const q = (n) => `'${n}'`;
  return [
    `  --font-ui: ${q(f.ui)}, system-ui, sans-serif;`,
    `  --font-head: ${q(f.head)}, ${q(f.ui)}, system-ui, sans-serif;`,
    `  --font-num: ${q(f.num)}, ui-monospace, monospace;`,
    `  --font-num-features: "${d.fontFeatures?.numbers ?? 'tnum'}";`,
    `  --fs: ${px(d.fs)};`,
    `  --rowH: ${px(d.rowH)};`,
    `  --rowHTouch: ${px(d.rowHTouch)};`,
    `  --heading-weight: ${d.headingWeight};`,
    `  --radiusSm: ${px(d.radiusSm)};`,
    `  --radiusMd: ${px(d.radiusMd)};`,
  ];
}

for (const [id, key] of Object.entries(map)) {
  const d = tokens.directions[key];
  const sel = id === 'tool' ? `:root, [data-theme="tool"]` : `[data-theme="${id}"]`;
  lines.push(`\n/* ${d.name} */`, `${sel} {`, ...themeVars(d), ...colorBlock(d.light), '}');
  const dsel = id === 'tool'
    ? `:root[data-scheme="dark"]:not([data-theme]), [data-theme="tool"][data-scheme="dark"]`
    : `[data-theme="${id}"][data-scheme="dark"]`;
  lines.push(`${dsel} {`, ...colorBlock(d.dark), '}');
}

// Print / PDF always uses «Бумажный лист» light.
const paper = tokens.directions[map.paper];
lines.push('\n/* Print / PDF: «Бумажный лист» */', '@media print {', '  :root, :root[data-theme], :root[data-scheme] {',
  ...themeVars(paper).map((l) => '  ' + l), ...colorBlock(paper.light).map((l) => '  ' + l), '  }', '}');

writeFileSync(join(here, '../src/styles/themes.css'), lines.join('\n') + '\n');
console.log('themes.css generated');
