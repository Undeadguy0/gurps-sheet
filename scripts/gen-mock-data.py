#!/usr/bin/env python3
"""Regenerates ui/src/mockEquipment.ts and ui/src/mockWeapons.ts from the plugin data
(basic-set-sample TOML + lang-ru Fluent) for the browser preview backend."""
import json, re, tomllib
from pathlib import Path

R = Path(__file__).resolve().parent.parent
DATA = R / "plugins/basic-set-sample/data"
RU = R / "plugins/lang-ru/locales/ru"


def ftl(path, prefix):
    out, key, desc = {}, None, None
    for line in path.read_text(encoding="utf-8").split("\n"):
        m = re.match(r"^([a-z0-9-]+) = (.*)$", line)
        if m:
            key = m.group(1)
            out[key] = {"name": m.group(2).strip(), "description": ""}
            desc = None
        elif key and line.strip() == ".description =":
            desc = []
            out[key]["_d"] = desc
        elif desc is not None and (line.startswith("        ") or not line.strip()):
            desc.append(line[8:])
    res = {}
    for k, v in out.items():
        if not k.startswith(prefix):
            continue
        d = "\n".join(v.pop("_d", [])).strip("\n")
        res[k[len(prefix):]] = {"name": v["name"], "description": d + "\n"}
    return res


def write(name, header, typ, const, defs, cat_const, cat):
    (R / "ui/src" / name).write_text(
        "// GENERATED by scripts/gen-mock-data.py from plugins/basic-set-sample and plugins/lang-ru\n"
        f"// for the browser preview backend. {header}\n"
        f"import type {{ {typ} }} from './types';\n\n"
        f"export const {const}: {typ}[] = {json.dumps(defs, ensure_ascii=False, indent=2)};\n\n"
        f"export const {cat_const}: Record<string, {{ name: string; description: string }}> = "
        f"{json.dumps(cat, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )


eq = tomllib.loads((DATA / "equipment.toml").read_text(encoding="utf-8"))["equipment"]
for e in eq:
    for k in ("weight", "cost"):
        if float(e[k]).is_integer():
            e[k] = int(e[k])
write("mockEquipment.ts", "Own-words texts; weights, costs and pages are unverified.",
      "EquipmentDef", "EQUIPMENT_DEFS", eq, "EQUIPMENT_CATALOG_RU",
      ftl(RU / "basic-set-equipment.ftl", "equipment-"))
ws = tomllib.loads((DATA / "weapons.toml").read_text(encoding="utf-8"))["weapons"]
write("mockWeapons.ts", "Own-words texts; stats and pages are unverified.",
      "WeaponDef", "WEAPON_DEFS", ws, "WEAPON_CATALOG_RU", ftl(RU / "basic-set-weapons.ftl", "weapon-"))
print(len(eq), len(ws))
